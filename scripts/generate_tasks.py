def main() -> None:
    TASKS_DIR.mkdir(exist_ok=True)
    for v in VARIANTS:
        path = TASKS_DIR / f"task_v{v['n']:02d}.md"
        path.write_text(render_task(v), encoding="utf-8")
        print("written", path.relative_to(ROOT))
    index = TASKS_DIR / "README.md"
    index.write_text(render_index(), encoding="utf-8")
    print("written", index.relative_to(ROOT))


if __name__ == "__main__":
    main()
